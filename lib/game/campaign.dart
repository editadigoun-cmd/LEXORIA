  const GameLevel({
    required this.id,
    required this.title,
    required this.category,
    required this.gridSize,
    required this.words,
    required this.timeLimitSeconds,
    required this.difficulty,
  });

  final int id;
  final String title;
  final String category;
  final int gridSize;
  final List<String> words;
  final int timeLimitSeconds;
  final String difficulty;
}

