  static final List<GameLevel> all = _build();

  static List<GameLevel> _build() {
    final levels = <GameLevel>[];
    final used = <String>{};
    var id = 1;
    for (final entry in _themes.entries) {
      final uniqueWords = entry.value.where((word) => used.add(word)).toList();
      if (uniqueWords.length != 50) {
        throw StateError('Theme ${entry.key} must contribute 50 globally unique words; got ${uniqueWords.length}.');
      }
      for (var stage = 0; stage < 10; stage++) {
        final start = stage * 5;
        final size = id <= 20 ? 8 : id <= 50 ? 9 : id <= 80 ? 10 : 12;
        levels.add(GameLevel(
          id: id,
          title: 'Level $id',
          category: entry.key,
          gridSize: size,
          words: List.unmodifiable(uniqueWords.sublist(start, start + 5)),
          timeLimitSeconds: id <= 20 ? 150 : id <= 60 ? 180 : 210,
          difficulty: id <= 20 ? 'Easy' : id <= 60 ? 'Intermediate' : 'Expert',
        ));
        id++;
      }
    }
    if (id != 101 || used.length != 500) {
      throw StateError('Campaign must contain 100 levels and 500 unique words.');
    }
    return List.unmodifiable(levels);
  }
